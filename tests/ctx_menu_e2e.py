"""Every right-click action, with a real right-click (Avi, 31.10: "so everything behind a right-click was never checked?").
Cue menu: edit / edit text / rename / duplicate / up / down / take out of slide show / delete.
Slide-show menu: open-close / edit / rename / duplicate / up / down / ungroup / delete.
Both languages; the menu stays inside the window; the live cue is never removed without asking."""
import asyncio, os
from playwright.async_api import async_playwright
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
FIX = os.environ.get('CUEY_FIXTURES') or os.path.join(ROOT, 'tests', 'fixtures')
URL = 'file://' + ROOT + '/app/cuey.html?nosplash&notour&lang='
res = []
def ok(n, c, extra=''):
    res.append(bool(c)); print(('PASS ' if c else 'FAIL ') + n + (('  -> ' + str(extra)[:300]) if extra and not c else ''), flush=True)

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(args=['--allow-file-access-from-files'])
        for lang in ('he', 'en'):
            ctx = await b.new_context(viewport={'width': 1280, 'height': 800}); pg = await ctx.new_page(); errs = []; sysd = []
            pg.on('pageerror', lambda e: errs.append(str(e))); pg.on('dialog', lambda d: (sysd.append(d.message), asyncio.ensure_future(d.dismiss())))
            await pg.goto(URL + lang); await pg.wait_for_timeout(600)
            await pg.set_input_files('#fileIn', [os.path.join(FIX, n) for n in ('red.png', 'green.png', 'blue.png', 'yellow.png')]); await pg.wait_for_timeout(1000)
            names = lambda: pg.evaluate("items.map(i=>i.name).join(',')")
            async def menu(i):
                await pg.click(f'#list .item[data-id="{await pg.evaluate(f"items[{i}].id")}"] .name', button='right'); await pg.wait_for_timeout(150)
                return await pg.evaluate("$('#ctxm')?[...$('#ctxm').querySelectorAll('[data-c]')].map(b=>b.dataset.c):[]")
            async def pick(c):
                await pg.click(f'#ctxm [data-c="{c}"]'); await pg.wait_for_timeout(200)
            cs = await menu(1)
            ok(f'[{lang}] right-click on a cue opens its menu', cs[:4] == ['edit', 'rename', 'dup', 'up'] and 'del' in cs, cs)
            inside = await pg.evaluate("(()=>{const r=$('#ctxm').getBoundingClientRect();return r.left>=0&&r.top>=0&&r.right<=innerWidth&&r.bottom<=innerHeight})()")
            ok(f'[{lang}] the menu is fully inside the window', inside)
            await pg.keyboard.press('Escape'); await pg.mouse.click(900, 500); await pg.wait_for_timeout(100)
            ok(f'[{lang}] clicking elsewhere closes it', not await pg.evaluate("!!$('#ctxm')"))
            await menu(1); await pick('edit')
            ok(f'[{lang}] Edit… opens the edit panel for that cue', await pg.evaluate("!$('#editDlg').hidden"))
            await pg.keyboard.press('Escape'); await pg.wait_for_timeout(200)
            await pg.evaluate("document.querySelectorAll('.dlg').forEach(d=>{if(d.id)d.hidden=true})")
            await menu(1); await pick('rename')
            ok(f'[{lang}] Rename turns the name into a text box', await pg.evaluate("!!document.querySelector('#list input.rn, #list .item input[type=text], #list .name input')"))
            await pg.keyboard.press('Control+A'); await pg.keyboard.type('שם חדש'); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(150)
            ok(f'[{lang}] …Enter keeps the new name', await pg.evaluate("items[1].name") == 'שם חדש', await names())
            await menu(1); await pick('dup')
            ok(f'[{lang}] Duplicate adds a copy right after it', await pg.evaluate("items.length===5&&items[2].name==='שם חדש'"), await names())
            await menu(2); await pick('del')
            ok(f'[{lang}] Delete removes that cue (not the live one: nothing is live)', await pg.evaluate("items.length===4"), await names())
            await menu(1); await pick('down')
            ok(f'[{lang}] Move down', await pg.evaluate("items[2].name==='שם חדש'"), await names())
            await menu(2); await pick('up')
            ok(f'[{lang}] Move up', await pg.evaluate("items[1].name==='שם חדש'"), await names())
            # the live cue: deleting it would blank the event screen — Cuey asks first
            await pg.evaluate("show(0)"); await pg.wait_for_timeout(300)
            await menu(0); await pick('del')
            q = await pg.evaluate("document.querySelector('.uiq')?document.querySelector('.uiq').innerText:''")
            ok(f'[{lang}] deleting the LIVE cue asks first (the audience would see it disappear)', bool(q), q)
            if q:
                await pg.click('.uiq [data-v=no]'); await pg.wait_for_timeout(150)
            ok(f'[{lang}] …Cancel: still there and still live', await pg.evaluate("items.length===4&&cur===0"))
            await menu(0); await pick('del'); await pg.click('.uiq .dang'); await pg.wait_for_timeout(200)
            ok(f'[{lang}] …Remove: gone, nothing live', await pg.evaluate("items.length===3&&cur===-1"))
            await pg.evaluate("(()=>{const it=newCardItem();it.name='x';items.unshift(it);render()})()"); await pg.wait_for_timeout(150)
            # text cue: Edit text
            await pg.evaluate("(()=>{const it=newCardItem();it.text={title:'כותרת',body:''};items.push(it);render()})()"); await pg.wait_for_timeout(200)
            cs = await menu(4)
            ok(f'[{lang}] a text cue also offers "edit text"', 'text' in cs, cs)
            await pick('text')
            ok(f'[{lang}] …which opens the text editor for that cue', await pg.evaluate("mk.it===items[4]&&!$('#mkDlg').hidden"))
            await pg.keyboard.press('Escape'); await pg.wait_for_timeout(150); await pg.evaluate("document.querySelectorAll('.dlg').forEach(d=>{if(d.id)d.hidden=true})")
            # slide show menu
            await pg.evaluate("sel.clear();sel.add(items[2].id);sel.add(items[3].id);makeGroup()"); await pg.wait_for_timeout(250)
            g = await pg.evaluate("Object.keys(groups)[0]")
            gs = await pg.evaluate("Object.keys(groups).length")
            ok(f'[{lang}] slide show made', gs == 1)
            await pg.evaluate(f"groups['{g}'].open=true;render()"); await pg.wait_for_timeout(150)
            n0 = await pg.evaluate(f"items.filter(x=>x.grp==='{g}').length")
            cs = await menu(await pg.evaluate(f"items.findIndex(x=>x.grp==='{g}')"))
            ok(f'[{lang}] a cue inside a slide show offers "take out"', 'out' in cs, cs)
            await pick('out')
            ok(f'[{lang}] …take out: it leaves the slide show, the rest stay', await pg.evaluate(f"items.filter(x=>x.grp==='{g}').length") == n0 - 1 and await pg.evaluate("items.length") == 5)
            await pg.click(f'#list .grpc[data-g="{g}"]', button='right'); await pg.wait_for_timeout(150)
            gm = await pg.evaluate("$('#ctxm')?[...$('#ctxm').querySelectorAll('[data-c]')].map(b=>b.dataset.c):[]")
            ok(f'[{lang}] right-click on a slide show opens its menu', gm == ['tog', 'edit', 'ren', 'copy', 'up', 'down', 'ungroup', 'del'], gm)
            await pick('copy')
            ok(f'[{lang}] Duplicate slide show', await pg.evaluate("Object.keys(groups).length") == 2)
            g2 = await pg.evaluate("Object.keys(groups)[1]")
            await pg.click(f'#list .grpc[data-g="{g2}"]', button='right'); await pg.wait_for_timeout(150); await pick('ungroup')
            ok(f'[{lang}] Ungroup keeps the cues, drops the slide show', await pg.evaluate(f"!groups['{g2}']&&items.every(x=>x.grp!=='{g2}')"))
            a0 = await pg.evaluate(f"grpRange('{g}')[0]")
            await pg.click(f'#list .grpc[data-g="{g}"]', button='right'); await pg.wait_for_timeout(150); await pick('up')
            a1 = await pg.evaluate(f"grpRange('{g}')[0]")
            ok(f'[{lang}] Move slide show up', a1 < a0, (a0, a1))
            await pg.click(f'#list .grpc[data-g="{g}"]', button='right'); await pg.wait_for_timeout(150); await pick('down')
            ok(f'[{lang}] Move slide show down', await pg.evaluate(f"grpRange('{g}')[0]") > a1)
            o0 = await pg.evaluate(f"!!groups['{g}'].open")
            await pg.click(f'#list .grpc[data-g="{g}"]', button='right'); await pg.wait_for_timeout(150); await pick('tog')
            ok(f'[{lang}] Open/close the slide show', await pg.evaluate(f"!!groups['{g}'].open") != o0)
            await pg.click(f'#list .grpc[data-g="{g}"]', button='right'); await pg.wait_for_timeout(150); await pick('ren')
            ok(f'[{lang}] Rename slide show gives a text box', await pg.evaluate("!!document.querySelector('#list .grpc input')"))
            await pg.keyboard.press('Escape'); await pg.wait_for_timeout(100)
            await pg.click(f'#list .grpc[data-g="{g}"]', button='right'); await pg.wait_for_timeout(150); await pick('edit')
            ok(f'[{lang}] Edit slide show opens its settings', await pg.evaluate(f"!$('#editDlg').hidden&&$('#editDlg').innerText.includes(groups['{g}'].name)"))
            await pg.keyboard.press('Escape'); await pg.wait_for_timeout(150); await pg.evaluate("document.querySelectorAll('.dlg').forEach(d=>{if(d.id)d.hidden=true})")
            await pg.click(f'#list .grpc[data-g="{g}"]', button='right'); await pg.wait_for_timeout(150); await pick('del')
            ok(f'[{lang}] Delete slide show asks first (in Cuey\'s window)', await pg.evaluate("!!document.querySelector('.uiq')"))
            await pg.click('.uiq [data-v=no]'); await pg.wait_for_timeout(100)
            # the Delete key on the live cue asks too
            await pg.evaluate("render()"); n = await pg.evaluate("items.length")
            await pg.evaluate("show(0);sel.clear();sel.add(items[0].id);render()"); await pg.wait_for_timeout(300)
            await pg.click(f'#list .item[data-id="{await pg.evaluate("items[0].id")}"] .name'); await pg.wait_for_timeout(150)
            await pg.evaluate("document.activeElement&&document.activeElement.blur()")
            await pg.keyboard.press('Delete'); await pg.wait_for_timeout(200)
            ok(f'[{lang}] Delete key on the live cue asks first', await pg.evaluate("!!document.querySelector('.uiq')"), await pg.evaluate("JSON.stringify({cur,sel:[...sel],n:items.length,dl:[...document.querySelectorAll('.dlg')].filter(d=>!d.hidden).map(d=>d.id||d.className),ae:document.activeElement&&document.activeElement.tagName,ctx:!!$('#ctxm')})"))
            if await pg.evaluate("!!document.querySelector('.uiq')"):
                await pg.click('.uiq [data-v=no]'); await pg.wait_for_timeout(150)
            ok(f'[{lang}] …Cancel keeps it live', await pg.evaluate("items.length") == n and await pg.evaluate("cur===0"))
            ok(f'[{lang}] no system alert / confirm', not sysd, sysd)
            ok(f'[{lang}] no page errors', not errs, errs[:3])
            await ctx.close()
        print(f'\n{sum(res)}/{len(res)} passed', flush=True)
        await b.close()
asyncio.run(main())
